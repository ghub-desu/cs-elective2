# 4. Cube Roots using Fixed-Point Iteration
# ==========================================================


# Fixed-Point Iteration
def fixed_point(g, x0, tolerance):

    x = x0

    print("Iteration        x_n                 Error")
    print("-----------------------------------------------")

    print(f"{0:<17}{x:<20.10f}-")

    for n in range(1, 1000):

        x_new = g(x)
        error = abs(x_new - x)

        print(f"{n:<17}{x_new:<20.10f}{error:.10f}")

        if error < tolerance:
            print("-----------------------------------------------")
            print(f"Answer: {x_new:.8f}")
            print(f"Iterations: {n}")
            return

        x = x_new


# ==========================================================
# 4(a) Cube root of 2
# ==========================================================

print("\n================================================")
print("4(a)  Cube root of 2")
print("================================================")

# g(x) = (2x + 2/x^2) / 3

def g4a(x):
    return (2 * x + 2 / x**2) / 3

fixed_point(g4a, 1, 0.5e-8)


