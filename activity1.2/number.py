# 3. Square Roots using Fixed-Point Iteration
# ==========================================================


# Fixed-Point Iteration
def fixed_point(g, x0, tolerance):

    x = x0

    print("Iteration        x_n                 Error")
    print("-----------------------------------------------")

    print(f"{0:<17}{x:<20.10f}-")

    for n in range(1, 1000):

        x_new = g(x)
        error = abs(x_new - x)

        print(f"{n:<17}{x_new:<20.10f}{error:.10f}")

        if error < tolerance:
            print("-----------------------------------------------")
            print(f"Answer: {x_new:.8f}")
            print(f"Iterations: {n}")
            return

        x = x_new


# ==========================================================
# 3(a) Square root of 3
# ==========================================================

print("\n================================================")
print("3(a)  Square root of 3")
print("================================================")

# x_(n+1) = 1/2 * (x_n + 3/x_n)

def g3a(x):
    return 0.5 * (x + 3 / x)

fixed_point(g3a, 1, 0.5e-8)


# ==========================================================
# 3(b) Square root of 5
# ==========================================================

print("\n================================================")
print("3(b)  Square root of 5")
