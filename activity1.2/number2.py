import math


# Fixed-Point Iteration
def fixed_point(g, x0, tolerance):

    x = x0

    print("Iteration        x_n                 Error")
    print("-----------------------------------------------")

    print(f"{0:<17}{x:<20.10f}-")

    for n in range(1, 1000):

        x_new = g(x)
        error = abs(x_new - x)

        print(f"{n:<17}{x_new:<20.10f}{error:.10f}")

        if error < tolerance:
            print("-----------------------------------------------")
            print(f"Answer: {x_new:.8f}")
            print(f"Iterations: {n}")
            return

        x = x_new


# ==========================================================
# 2(a) x^5 + x = 1
# ==========================================================

print("\n================================================")
print("2(a)  x^5 + x = 1")
print("================================================")

# x = (1 - x)^(1/5)
def g2a(x):
    return (1 - x) ** (1 / 5)

fixed_point(g2a, 0.5, 0.5e-8)


# ==========================================================
# 2(b) sin(x) = 6x + 5
# ==========================================================

print("\n================================================")
print("2(b)  sin(x) = 6x + 5")
print("================================================")

# x = (sin(x) - 5) / 6
def g2b(x):
    return (math.sin(x) - 5) / 6

fixed_point(g2b, 0, 0.5e-8)


# ==========================================================
# 2(c) ln(x) + x^2 = 3
# ==========================================================

print("\n================================================")
print("2(c)  ln(x) + x^2 = 3")
print("================================================")

# x = sqrt(3 - ln(x))
def g2c(x):
    return math.sqrt(3 - math.log(x))

fixed_point(g2c, 1, 0.5e-8)
