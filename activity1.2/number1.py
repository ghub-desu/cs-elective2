import math


# Fixed-Point Iteration
def fixed_point(g, x0, tolerance):

    x = x0

    print("Iteration        x_n                 Error")
    print("-----------------------------------------------")

    print(f"{0:<17}{x:<20.10f}-")

    for n in range(1, 1000):

        x_new = g(x)
        error = abs(x_new - x)

        print(f"{n:<17}{x_new:<20.10f}{error:.10f}")

        if error < tolerance:
            print("-----------------------------------------------")
            print(f"Answer: {x_new:.8f}")
            print(f"Iterations: {n}")
            return

        x = x_new


# ==========================================================
# 1(a) x^3 = 2x + 2
# ==========================================================

print("\n================================================")
print("1(a)  x^3 = 2x + 2")
print("================================================")

# x = cube root(2x + 2)
def g1a(x):
    return (2 * x + 2) ** (1 / 3)

fixed_point(g1a, 1, 0.5e-8)


# ==========================================================
# 1(b) e^x + x = 7
# ==========================================================

print("\n================================================")
print("1(b)  e^x + x = 7")
print("================================================")

# x = ln(7 - x)
def g1b(x):
    return math.log(7 - x)

fixed_point(g1b, 1, 0.5e-8)


# ==========================================================
# 1(c) e^x + sin(x) = 4
# ==========================================================

print("\n================================================")
print("1(c)  e^x + sin(x) = 4")
print("================================================")

# x = ln(4 - sin(x))
def g1c(x):
    return math.log(4 - math.sin(x))

fixed_point(g1c, 1, 0.5e-8)
